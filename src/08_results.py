"""Step 8: write RESULTS.md from the CSV tables in outputs/tables (no number is typed by hand)."""
import pandas as pd

from common import FEATURES, FS_LABEL, PREDICTIONS, ROOT, TABLES

MODEL_LABEL = {"LogisticRegression": "Logistic Regression", "DecisionTree": "Decision Tree",
               "RandomForest": "Random Forest", "LinearRegression": "Linear Regression"}


def t(name):
    return pd.read_csv(TABLES / name)


def kv(name):
    return pd.read_csv(TABLES / name).set_index("stat")["value"]


def md(df: pd.DataFrame, digits=4) -> str:
    def fmt(v):
        if isinstance(v, float):
            return f"{v:,.{digits}f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v).replace("|", "\\|")
    head = "| " + " | ".join(str(c).replace("|", "\\|") for c in df.columns) + " |"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def ci(row, d=4, mean="mean_diff"):
    return f"{row[mean]:+.{d}f} [95% CI {row['ci95_low']:+.{d}f}, {row['ci95_high']:+.{d}f}]"


def main():
    ss, ps = kv("sample_stats.csv"), kv("population_stats.csv")
    ksel, prof = t("k_selection.csv"), t("cluster_profiles.csv").set_index("segment")
    cci, rci = t("classification_ci.csv"), t("regression_ci.csv")
    clf, tune = t("classification_metrics.csv"), t("threshold_tuning.csv")
    boot, val = t("ablation_bootstrap.csv"), t("classifier_validation.csv")
    hur, cal, hboot = t("hurdle_metrics.csv"), t("hurdle_calibration.csv"), t("hurdle_bootstrap.csv")
    err, leak = t("regression_error_concentration.csv"), t("leakage_audit.csv")
    shap_all, shap_seg = t("shap_importance.csv"), t("shap_top5_per_segment.csv")
    kc = t("k_sensitivity_conclusions.csv")
    sp = t("split_sizes.csv").set_index("part")
    L = []
    w = L.append

    w("# RESULTS\n")
    w("Generated by `src/08_results.py` from `outputs/tables/*.csv` (all numbers come from the pipeline run; "
      "re-run with `python run_all.py`). Seed = 42. Figures: `outputs/figures/`. Report package (tables T1-T6 as "
      "CSV + markdown, architecture diagram, figures list, methods facts, worked example): `outputs/report/`.\n")

    # ---------------- data ----------------
    w("## Data\n")
    w(f"- Raw `2019-Oct.csv`: {int(ss['raw_rows']):,} events, {int(ss['raw_users']):,} users.")
    w(f"- Sample (user_id % 10 == 0): {int(ss['sample_rows']):,} events, {int(ss['sample_users']):,} users "
      f"({float(ss['sample_user_share']):.2%} of users). Events: view {int(ss['events_view']):,}, "
      f"cart {int(ss['events_cart']):,}, purchase {int(ss['events_purchase']):,}, "
      f"remove_from_cart {int(ss['events_remove_from_cart']):,}.")
    w(f"- Observation window Oct 1-24: {int(ps['obs_window_events']):,} events. Prediction window Oct 25-31: "
      f"{int(ps['pred_window_events']):,} events.")
    w(f"- Population (>=1 event Oct 1-24): {int(ps['population_users']):,} users; train {int(ps['train_users']):,} "
      f"(inner train {int(sp.loc['inner train (model choice / thresholds)', 'users']):,} + validation "
      f"{int(sp.loc['validation (part of train)', 'users']):,}) / test {int(ps['test_users']):,}.")
    w(f"- Class balance: will_purchase = 1 for {int(ps['will_purchase_positive']):,} users "
      f"({float(ps['will_purchase_rate']):.2%}; train {float(ps['will_purchase_rate_train']):.2%}, "
      f"test {float(ps['will_purchase_rate_test']):.2%}).")
    w(f"- future_spend: mean {float(ps['future_spend_mean_all']):,.2f} over all users; among buyers mean "
      f"{float(ps['future_spend_mean_buyers']):,.2f}, median {float(ps['future_spend_median_buyers']):,.2f}, "
      f"max {float(ps['future_spend_max']):,.2f}.\n")

    # ---------------- clustering ----------------
    k = int(ksel["chosen_k"].iloc[0])
    w("## Segmentation (K-means)\n")
    w(f"Decision: {ksel['decision'].iloc[0]}. Chosen K = {k}. Names come from the Oct 1-24 profile "
      "(rule and numbers: `outputs/report/cluster_naming.md`).\n")
    w(md(ksel[["k", "inertia", "silhouette"]].assign(inertia=lambda d: d["inertia"].round(0).astype(int)), 4) + "\n")
    cols = ["n_users", "share", "has_purchased", "monetary", "frequency", "recency_days", "n_sessions", "n_views",
            "n_carts", "days_active", "pred_window_purchase_rate", "pred_window_mean_spend"]
    pp = prof[cols].reset_index()
    pp["n_users"] = pp["n_users"].astype(int)
    w("Segment profiles (means; last two columns are descriptive only, not used for clustering or naming):\n")
    w(md(pp, 3) + "\n")

    # ---------------- classification ----------------
    w("## Classification: will_purchase (test set, class_weight='balanced')\n")
    g = cci.set_index(["feature_set", "model", "metric"])
    rows = []
    for fs in FS_LABEL:
        for m in MODEL_LABEL:
            if m == "LinearRegression":
                continue
            tr = tune.set_index(["feature_set", "model"]).loc[(fs, m)]
            rows.append({"feature set": FS_LABEL[fs], "model": MODEL_LABEL[m],
                         "ROC-AUC": g.loc[(fs, m, "roc_auc"), "value"], "PR-AUC": g.loc[(fs, m, "pr_auc"), "value"],
                         "F1 @0.5": tr["test_f1_at_0.5"], "P @0.5": tr["test_precision_at_0.5"],
                         "R @0.5": tr["test_recall_at_0.5"], "tuned thr": tr["tuned_threshold_from_validation"],
                         "F1 @tuned": tr["test_f1_at_tuned"], "P @tuned": tr["test_precision_at_tuned"],
                         "R @tuned": tr["test_recall_at_tuned"]})
    w(md(pd.DataFrame(rows), 4) + "\n")
    w("Tuned threshold = F1-maximising threshold on the validation split (part of train). 95% CIs for every "
      "metric: `outputs/report/tables/T2_classification.md`.\n")

    # ---------------- ablation ----------------
    w("## Ablation: which feature set won\n")
    bi = boot.set_index(["metric", "model", "comparison"])
    ba, cb = "b_rfm_behav minus a_rfm", "c_rfm_behav_cluster minus b_rfm_behav"
    for m in ["LogisticRegression", "DecisionTree", "RandomForest"]:
        sub = clf[clf["model"] == m].set_index("feature_set")["roc_auc"]
        w(f"- {MODEL_LABEL[m]}, ROC-AUC: best = {FS_LABEL[sub.idxmax()]} ({sub.max():.4f}). "
          f"(b)-(a) {ci(bi.loc[('roc_auc', m, ba)])}; (c)-(b) {ci(bi.loc[('roc_auc', m, cb)])}.")
    for m in ["LogisticRegression", "DecisionTree", "RandomForest"]:
        sub = tune[tune["model"] == m].set_index("feature_set")
        w(f"- {MODEL_LABEL[m]}, F1: at 0.5 best = {FS_LABEL[sub['test_f1_at_0.5'].idxmax()]}; at tuned threshold "
          f"best = {FS_LABEL[sub['test_f1_at_tuned'].idxmax()]} ({sub['test_f1_at_tuned'].max():.4f}). Tuned F1 "
          f"(b)-(a) {ci(bi.loc[('f1_at_tuned', m, ba)])}; (c)-(b) {ci(bi.loc[('f1_at_tuned', m, cb)])}.")
    for m in ["LinearRegression", "DecisionTree", "RandomForest", "Hurdle"]:
        if m == "Hurdle":
            h = hur[(hur["subset"] == "all_test_users") & hur["model"].str.contains("prior-corrected")]
            sub, name = h.set_index("feature_set")["RMSE"], "Hurdle (prior-corrected)"
        else:
            sub, name = t("regression_metrics.csv").query("model == @m").set_index("feature_set")["RMSE"], \
                f"{MODEL_LABEL[m]} (single-stage)"
        w(f"- {name}, RMSE: best = {FS_LABEL[sub.idxmin()]} ({sub.min():.2f}). "
          f"(b)-(a) {ci(bi.loc[('RMSE', m, ba)], 2)}; (c)-(b) {ci(bi.loc[('RMSE', m, cb)], 2)}.")
    w(f"- Paired bootstrap: 500 resamples of the test users (ROC-AUC/F1: higher = better; RMSE: lower = better). "
      "Table: `outputs/tables/ablation_bootstrap.csv`, `outputs/report/tables/T2b_*.md`.\n")

    # ---------------- hurdle ----------------
    w("## Spend: single-stage vs hurdle (all test users)\n")
    w(f"Stage 1 = classifier with the highest validation ROC-AUC, probabilities prior-corrected for "
      f"class_weight='balanced'. Stage 2 = Random Forest regressor on {int(cal['stage2_train_buyers'].iloc[0]):,} "
      "train buyers (future_spend > 0).\n")
    r = rci[rci["subset"] == "all_test_users"].pivot_table(index=["feature_set", "model"], columns="metric",
                                                            values=["value", "ci95_low", "ci95_high"])
    rows = []
    for fs in FS_LABEL:
        for m in ["LinearRegression (single-stage)", "DecisionTree (single-stage)", "RandomForest (single-stage)",
                  "Hurdle (prior-corrected)"]:
            x = r.loc[(fs, m)]
            rows.append({"feature set": FS_LABEL[fs], "model": m} |
                        {f"{met} [95% CI]": f"{x[('value', met)]:,.3f} [{x[('ci95_low', met)]:,.3f}, "
                                            f"{x[('ci95_high', met)]:,.3f}]" for met in ["MAE", "RMSE", "R2"]})
    w(md(pd.DataFrame(rows)) + "\n")
    w("Hurdle minus single-stage (paired bootstrap, negative = hurdle better):\n")
    hb = hboot.assign(feature_set=hboot["feature_set"].map(FS_LABEL))
    w(md(hb[["feature_set", "comparison", "metric", "mean_diff", "ci95_low", "ci95_high"]], 3) + "\n")
    w("Buyers-only metrics and the raw (uncorrected) hurdle: `outputs/tables/hurdle_metrics.csv`, "
      "`outputs/report/tables/T3_spend.md`.\n")

    # ---------------- K sensitivity ----------------
    w("## K sensitivity (feature set (c) and segment profiles, K = 2 / 3 / 4)\n")
    kc_cols = [c for c in kc.columns if c.endswith("value") or "same conclusion" in c]
    w(md(kc[["check"] + kc_cols]) + "\n")
    w("Full tables: `outputs/tables/k_sensitivity_{metrics,profiles,conclusions}.csv`.\n")

    # ---------------- leakage ----------------
    w("## Leakage audit (DELIBERATELY FLAWED setup, for comparison only)\n")
    w("Leaky = features rebuilt from Oct 1-31 (overlapping the Oct 25-31 target window), same users, targets, "
      "split and models. Inflation = leaky minus honest. Full table: `outputs/report/tables/T4_leakage_audit.md`.\n")
    la = leak[leak["metric"].isin(["roc_auc", "R2"])]
    for (task, met), grp in la.groupby(["task", "metric"]):
        w(f"- {task} {met}: honest {grp['honest'].min():.4f} to {grp['honest'].max():.4f}; leaky "
          f"{grp['leaky'].min():.4f} to {grp['leaky'].max():.4f}; inflation {grp['inflation_leaky_minus_honest'].min():+.4f} "
          f"to {grp['inflation_leaky_minus_honest'].max():+.4f}.")
    w("")

    # ---------------- SHAP ----------------
    vb = val[val["model"] == "RandomForest"].sort_values("val_roc_auc", ascending=False).iloc[0]
    w("## Explainability (SHAP, TreeExplainer)\n")
    w(f"Model: Random Forest classifier on {FS_LABEL[vb['feature_set']]} (highest validation ROC-AUC among RF "
      f"classifiers, {vb['val_roc_auc']:.4f}). 2,000 random test users; positive class.\n")
    w(md(shap_all.head(8)[["label", "mean_abs_shap"]].rename(columns={"label": "feature"}), 5) + "\n")
    for variant in ["all_features", "excluding_seg_dummies"]:
        s = shap_seg[shap_seg["ranking"] == variant]
        piv = s.pivot(index="rank", columns="segment", values="label").reset_index()
        w(f"Top 5 per segment ({variant.replace('_', ' ')}; up to 1,000 test users per segment):\n")
        w(md(piv, 0) + "\n")

    # ---------------- caveats ----------------
    lr_err = err.set_index("prediction").loc["reg|a_rfm|LinearRegression"]
    rf_err = err.set_index("prediction").loc["reg|b_rfm_behav|RandomForest"]
    rf_te = clf[clf["model"] == "RandomForest"].set_index("feature_set")["roc_auc"]
    pr, fe = pd.read_parquet(PREDICTIONS), pd.read_parquet(FEATURES)
    u_max = pr["reg|a_rfm|LinearRegression"].idxmax()
    te_mon = fe.loc[fe["split"] == "test", "monetary"]
    cb_auc = boot[(boot["metric"] == "roc_auc") & (boot["comparison"] == cb)]
    cbb = cal.set_index("feature_set").loc["b_rfm_behav"]
    tu = tune.set_index(["feature_set", "model"])
    changed = [(c, kk) for c in [x for x in kc.columns if "same conclusion" in x]
               for kk in kc.loc[kc[c] == "NO", "check"]]
    w("## Caveats\n")
    w(f"- `remove_from_cart` has {int(ss['events_remove_from_cart'])} events in the 10% user sample (event types "
      "were not counted in the full file), so n_remove_from_cart is constant 0 and was dropped from all models.")
    w(f"- K = {k} came from the default rule, not from agreement: elbow K = {int(ksel['elbow_k'].iloc[0])}, "
      f"best silhouette K = {int(ksel['best_silhouette_k'].iloc[0])}.")
    w("- K sensitivity: " + ("no listed conclusion changes with K=2 or K=4." if not changed else
                             "conclusions that differ from K=3: " + "; ".join(f"{c.split(':')[0]}: {kk}"
                                                                             for c, kk in changed) + "."))
    w(f"- Tuned thresholds are high ({tune['tuned_threshold_from_validation'].min():.4f} to "
      f"{tune['tuned_threshold_from_validation'].max():.4f}) because class_weight='balanced' inflates probabilities "
      f"(mean raw P = {cbb['mean_p_raw_balanced']:.4f} vs test purchase rate {cbb['test_purchase_rate']:.4f} for "
      f"{FS_LABEL['b_rfm_behav']}); the hurdle uses prior-corrected probabilities.")
    w(f"- Random Forest (c) vs (b): tuned F1 {tu.loc[('c_rfm_behav_cluster', 'RandomForest'), 'test_f1_at_tuned']:.4f} "
      f"vs {tu.loc[('b_rfm_behav', 'RandomForest'), 'test_f1_at_tuned']:.4f} (thresholds "
      f"{tu.loc[('c_rfm_behav_cluster', 'RandomForest'), 'tuned_threshold_from_validation']:.4f} vs "
      f"{tu.loc[('b_rfm_behav', 'RandomForest'), 'tuned_threshold_from_validation']:.4f}), while ROC-AUC is "
      f"{rf_te['c_rfm_behav_cluster']:.4f} vs {rf_te['b_rfm_behav']:.4f}. The F1 gap comes from the operating point, "
      "not from better ranking.")
    dt_cb = bi.loc[("f1_at_tuned", "DecisionTree", cb)]
    w(f"- Decision Tree (b) and (c) have the same tuned threshold "
      f"({tu.loc[('b_rfm_behav', 'DecisionTree'), 'tuned_threshold_from_validation']:.4f}) and identical test "
      f"precision/recall/F1 at it (tuned-F1 difference {dt_cb['mean_diff']:+.4f}, CI [{dt_cb['ci95_low']:+.4f}, "
      f"{dt_cb['ci95_high']:+.4f}]), although their ROC-AUC differs.")
    w(f"- (c) vs (b) ROC-AUC is small for every classifier (largest |difference| = "
      f"{cb_auc['mean_diff'].abs().max():.4f}); RF validation ranks (c) first, RF test ranks {FS_LABEL[rf_te.idxmax()]} first.")
    w(f"- future_spend is heavy-tailed; RMSE/R2 are driven by a few users. Top-10 test users = "
      f"{lr_err['share_of_SSE_from_top10_users']:.1%} of Linear Regression (a) squared error and "
      f"{rf_err['share_of_SSE_from_top10_users']:.1%} for Random Forest (b). Linear Regression max prediction "
      f"{lr_err['max_prediction']:,.0f} for a test user with obs-window monetary {fe.loc[u_max, 'monetary']:,.2f} "
      f"(largest in test: {te_mon.max():,.2f}) whose actual future_spend is {pr.loc[u_max, 'future_spend']:,.2f}.")
    w("- Per-segment SHAP: segment indicators are constant within a segment; their SHAP values reflect the gap to "
      "the global baseline (second ranking excludes them).")
    w(f"- {int(ps['pred_window_purchasers_not_in_population']):,} sampled users bought in Oct 25-31 without any "
      "Oct 1-24 event; they are outside the population by design.")
    w(f"- Data quirks kept as-is: {int(ss['exact_duplicate_rows_in_sample']):,} exact duplicate rows in the sample; "
      f"{int(ps['users_with_avg_session_over_24h']):,} users with mean session duration > 24 h.")
    w("- Hyperparameters are fixed (not tuned); one month, one split. Bootstrap CIs cover test-set sampling only, "
      "not training variance. Timestamps are UTC.")

    text = "\n".join(L) + "\n"
    (ROOT / "RESULTS.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
